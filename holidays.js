// تعطیلات رسمی بازار (میلادی، YYYY-MM-DD)
// ۱) فهرست دقیق (MANUAL): تا آخرین تاریخی که خودت وارد کرده‌ای.
// ۲) بعد از آخرین تاریخ فهرست، تعطیلات قمری به‌صورت خودکار «تخمین» زده می‌شود (ممکن است با رؤیت هلال یک روز اختلاف داشته باشد)
//    و تعطیلات ثابت شمسی را خود content.js خودکار حساب می‌کند.
// ۳) افزونه اگر ببیند امروز معامله انجام شده، حتی در «تعطیلی» هشدار می‌دهد؛ پس خطای تخمین خودش را نشان می‌دهد.
(function () {
  var MANUAL = [
  "2026-02-11",
  "2026-03-20",
  "2026-03-21",
  "2026-03-22",
  "2026-03-23",
  "2026-03-24",
  "2026-04-01",
  "2026-04-02",
  "2026-04-14",
  "2026-05-27",
  "2026-06-04",
  "2026-06-05",
  "2026-06-24",
  "2026-06-25",
  "2026-08-04",
  "2026-08-12",
  "2026-08-13",
  "2026-08-21",
  "2026-08-30",
  "2026-11-13",
  "2026-12-23",
  "2027-01-06",
  "2027-01-24",
  "2027-02-11",
  "2027-02-28",
  "2027-03-10",
  "2027-03-11",
  "2027-03-20"
];
  var all = MANUAL.slice();
  try {
    var last = MANUAL.slice().sort().pop();
    var EV = { "1-9":1, "1-10":1, "2-20":1, "2-28":1, "2-30":1, "3-17":1, "6-20":1, "7-13":1, "7-27":1,
               "8-15":1, "9-21":1, "10-1":1, "10-2":1, "10-25":1, "12-10":1, "12-18":1 };
    var fmt = new Intl.DateTimeFormat("en-u-ca-islamic-umalqura-nu-latn", { timeZone: "UTC", month: "numeric", day: "numeric" });
    var d = new Date(last + "T12:00:00Z");
    var end = new Date(Date.now() + 3 * 366 * 864e5);
    for (d = new Date(d.getTime() + 864e5); d <= end; d = new Date(d.getTime() + 864e5)) {
      var mo, dd;
      fmt.formatToParts(d).forEach(function (x) { if (x.type === "month") mo = x.value; if (x.type === "day") dd = x.value; });
      if (EV[Number(mo) + "-" + Number(dd)]) all.push(d.toISOString().slice(0, 10));
    }
  } catch (e) {}
  window.TSEXT_HOLIDAYS = all;
})();
